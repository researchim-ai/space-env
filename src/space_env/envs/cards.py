"""Карточка среды: что лежит в наблюдении, что значит действие и когда эпизод успешен."""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class EnvCard:
    env_id: str
    observation: tuple[str, ...]
    action: str
    success: str


def observation_index(env_id: str, field: str) -> int:
    """Позиция поля в векторе наблюдения. Политика берёт число отсюда, не из зашитого индекса."""
    return ENV_CARDS[env_id].observation.index(field)


def _per_vehicle(count: int, fields: tuple[str, ...], tail: tuple[str, ...]) -> tuple[str, ...]:
    names: list[str] = []
    for index in range(1, count + 1):
        names.extend(f"{field} {index}" for field in fields)
    names.extend(tail)
    return tuple(names)


